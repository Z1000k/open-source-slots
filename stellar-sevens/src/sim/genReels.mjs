/**
 * Generate src/engine/config/reelSets.ts from the slotopol data file.
 *
 * The strips are read straight out of slotopol/alwayshot_data.yaml rather than
 * typed by hand, so there is no transcription to get wrong. src/sim/checkReels.ts
 * re-reads the same yaml afterwards and asserts the generated TS still matches.
 *
 *   node src/sim/genReels.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const YAML = resolve(here, '../../slotopol/alwayshot_data.yaml');
const OUT = resolve(here, '../engine/config/reelSets.ts');

/** The original Always Hot strips (the set alwayshot_calc.lua ships with). */
const ORIGINAL_RTP = 95.504233;

export function parseYaml(text) {
  const sets = [];
  let current = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trimEnd();
    const head = /^(\d+\.\d+):\s*$/.exec(line);
    if (head) {
      current = { rtp: Number(head[1]), reels: [] };
      sets.push(current);
      continue;
    }
    const strip = /^\s*-\s*\[([\d,\s]+)\]\s*$/.exec(line);
    if (strip && current) {
      current.reels.push(strip[1].split(',').map((n) => Number(n.trim())));
    }
  }
  return sets;
}

const sets = parseYaml(readFileSync(YAML, 'utf8'));
if (sets.length === 0) throw new Error('no reel sets parsed');

for (const s of sets) {
  if (s.reels.length !== 3) throw new Error(`set ${s.rtp} has ${s.reels.length} reels, want 3`);
  const [a, b, c] = s.reels.map((r) => r.join(','));
  if (a !== b || a !== c) throw new Error(`set ${s.rtp} has reels that are not identical`);
  for (const n of s.reels[0]) {
    if (!Number.isInteger(n) || n < 1 || n > 9) throw new Error(`set ${s.rtp} has bad symbol ${n}`);
  }
}
if (!sets.some((s) => s.rtp === ORIGINAL_RTP)) {
  throw new Error(`original set ${ORIGINAL_RTP} missing from the yaml`);
}

const body = sets
  .map((s) => {
    const strip = s.reels[0];
    const n = strip.length;
    const note =
      s.rtp === ORIGINAL_RTP
        ? `    // ORIGINAL Always Hot strips (the set alwayshot_calc.lua ships with).\n` +
          `    // strip length ${n}, reshuffles ${n}^3 = ${n ** 3}\n`
        : `    // strip length ${n}, reshuffles ${n}^3 = ${n ** 3}\n`;
    return `  {\n${note}    rtp: ${s.rtp.toFixed(6)},\n    strip: [${strip.join(', ')}],\n  },`;
  })
  .join('\n');

const activeIndex = sets.findIndex((s) => s.rtp === ORIGINAL_RTP);

const out = `import type { SymbolId } from '../types';
import { SYMBOL_ORDER } from '../types';

/**
 * GENERATED by src/sim/genReels.mjs from slotopol/alwayshot_data.yaml. Do not
 * edit by hand; re-run \`npm run gen:reels\` instead, then \`npm run sim:reels\`
 * to prove the file still matches the yaml.
 *
 * Numeric symbol ids are slotopol's, 1-based, see SYMBOL_ORDER. In the yaml all
 * three reels of every set are the SAME strip, so each set is stored once here
 * and expanded to three. Each rtp is the figure slotopol publishes for that
 * set; src/sim/exact.ts reproduces every one of them by full enumeration.
 */
const RAW: { rtp: number; strip: number[] }[] = [
${body}
];

export interface ReelSet {
  /** the RTP slotopol publishes for this set, in percent */
  rtp: number;
  /** reels[reel] = full strip of symbols; all three reels are identical */
  reels: SymbolId[][];
}

export const REEL_SETS: ReelSet[] = RAW.map((s) => {
  const strip = s.strip.map((n) => SYMBOL_ORDER[n - 1]);
  return { rtp: s.rtp, reels: [strip, strip, strip] };
});

/** The original Always Hot reels (${ORIGINAL_RTP}%) - the set the game deals. */
export const ACTIVE_REELS: ReelSet = REEL_SETS[${activeIndex}];
`;

writeFileSync(OUT, out);
console.log(
  `wrote ${OUT}\n${sets.length} reel sets, RTP ${sets[0].rtp}% to ${sets[sets.length - 1].rtp}%, ` +
    `active index ${activeIndex} (${ORIGINAL_RTP}%)`,
);
