/**
 * Generates src/engine/config/reelSets.ts straight from slotopol's
 * cashfarm_data.yaml, so the strips cannot be mistyped. Also lifts the par
 * sheet slotopol publishes above each set (lined / scatter / farm figures)
 * into the file, giving src/sim/exact.ts its verification targets.
 *
 * Run: node src/sim/genReels.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const yaml = fs.readFileSync(path.join(root, 'slotopol', 'cashfarm_data.yaml'), 'utf8');

const lines = yaml.split(/\r?\n/);
const sets = [];
let pending = []; // comment lines seen since the last set

for (const raw of lines) {
  const line = raw.trimEnd();
  if (line.startsWith('#')) {
    pending.push(line.slice(1).trim());
    continue;
  }
  const head = /^(\d+\.\d+):$/.exec(line.trim());
  if (head) {
    sets.push({ rtp: Number(head[1]), comments: pending, reels: [] });
    pending = [];
    continue;
  }
  const reel = /^-\s*\[(.+?)\]/.exec(line.trim());
  if (reel && sets.length) {
    sets[sets.length - 1].reels.push(reel[1].split(',').map((n) => Number(n.trim())));
  }
}

if (sets.length !== 12) throw new Error(`expected 12 reel sets, parsed ${sets.length}`);

for (const s of sets) {
  if (s.reels.length !== 5) throw new Error(`set ${s.rtp}: expected 5 reels, got ${s.reels.length}`);
  for (const r of s.reels) {
    if (r.some((v) => !Number.isInteger(v) || v < 1 || v > 13)) {
      throw new Error(`set ${s.rtp}: symbol id out of range`);
    }
  }
}

/** Pull the numbers slotopol published for a set out of its comment block. */
function parsheet(comments) {
  const text = comments.join('\n');
  const sym = /symbols:\s*([\d.]+)\(lined\)\s*\+\s*([\d.]+)\(scatter\)\s*=\s*([\d.]+)%/.exec(text);
  const farm = /farm bonuses:\s*hit rate 1\/([\d.]+),\s*rtp\s*=\s*([\d.]+)%/.exec(text);
  const casc = /Mcascade\s*=\s*([\d.]+).*?Ncascmax\s*=\s*(\d+)/s.exec(text);
  const total = /RTP\s*=\s*[\d.]+\(sym\)\s*\+\s*[\d.]+\(farm\)\s*=\s*([\d.]+)%/.exec(text);
  if (!sym || !farm || !total) throw new Error('par sheet not found in:\n' + text);
  // N[k] = how many grids were scanned at fall level k-1, terminal empty scan
  // included. N[1] is every stop, N[2] is every paying base spin.
  const chain = [];
  for (const m of text.matchAll(/N\[(\d)\]\s*=\s*(\d+)/g)) chain[Number(m[1])] = Number(m[2]);
  return {
    symRtp: Number(sym[3]),
    farmHitRate: Number(farm[1]),
    farmRtp: Number(farm[2]),
    mcascade: casc ? Number(casc[1]) : null,
    ncascmax: casc ? Number(casc[2]) : null,
    chain: chain.slice(2).map((n) => n ?? 0),
    totalRtp: Number(total[1]),
  };
}

const body = sets
  .map((s) => {
    const p = parsheet(s.comments);
    const len = s.reels.map((r) => r.length).join(', ');
    return `  {
    // reels lengths [${len}], symbols ${p.symRtp}% + farm ${p.farmRtp}% (hit 1/${p.farmHitRate})
    rtp: ${s.rtp.toFixed(6)},
    parsheet: { symRtp: ${p.symRtp}, farmHitRate: ${p.farmHitRate}, farmRtp: ${p.farmRtp}, mcascade: ${p.mcascade}, ncascmax: ${p.ncascmax}, chain: [${p.chain.join(', ')}] },
    reels: [
${s.reels.map((r) => `      [${r.join(', ')}],`).join('\n')}
    ],
  },`;
  })
  .join('\n');

const out = `import type { SymbolId } from '../types';
import { SYMBOL_ORDER } from '../types';

/**
 * GENERATED by src/sim/genReels.mjs from slotopol/cashfarm_data.yaml.
 * Do not hand edit; re-run the generator instead.
 *
 * Reel strips copied verbatim from slotopol/server (MIT), novomatic/cashfarm.
 * Each set's rtp is slotopol's published full-game figure (base symbols with
 * cascades, plus the farm bonus). \`parsheet\` carries the rest of slotopol's
 * own numbers for that set so src/sim/exact.ts can check our engine against
 * them line by line.
 */
export interface ReelSetParSheet {
  /** lined + scatter RTP %, cascades included, bonus excluded */
  symRtp: number;
  /** one farm bonus per this many base spins */
  farmHitRate: number;
  /** farm bonus RTP % */
  farmRtp: number;
  /** total pays / base-spin pays */
  mcascade: number | null;
  /** number of fall levels ever reached, terminal empty scan included */
  ncascmax: number | null;
  /** slotopol's N[2..5]: grids scanned at fall level 1, 2, 3, 4 */
  chain: number[];
}

export interface ReelSet {
  rtp: number;
  parsheet: ReelSetParSheet;
  reels: number[][];
}

const RAW: ReelSet[] = [
${body}
];

/** Numeric strips mapped to our symbol names. */
export const REEL_SETS: { rtp: number; parsheet: ReelSetParSheet; reels: SymbolId[][] }[] = RAW.map(
  (set) => ({
    rtp: set.rtp,
    parsheet: set.parsheet,
    reels: set.reels.map((reel) => reel.map((id) => SYMBOL_ORDER[id - 1])),
  }),
);

export const RAW_REEL_SETS = RAW;

/**
 * The set the game actually ships on: Cash Farm's original 95.55% par.
 * Standing rule on this project is to ship every port on its original RTP.
 */
export const ACTIVE_RTP = 95.548865;

export const ACTIVE_SET = REEL_SETS.find((s) => s.rtp === ACTIVE_RTP)!;
export const ACTIVE_REELS = ACTIVE_SET.reels;
`;

const dest = path.join(root, 'src', 'engine', 'config', 'reelSets.ts');
fs.writeFileSync(dest, out);
console.log(`wrote ${dest}`);
console.log(`${sets.length} sets:`, sets.map((s) => s.rtp).join(', '));
