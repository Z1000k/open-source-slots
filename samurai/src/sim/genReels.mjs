/**
 * Generate src/engine/config/reelSets.ts from the slotopol data file.
 *
 * The strips are read straight out of slotopol/katana_data.yaml rather than
 * typed by hand, so there is no transcription to get wrong.
 * src/sim/checkReels.ts re-reads the same yaml afterwards and asserts the
 * generated TS still matches.
 *
 *   node src/sim/genReels.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const YAML = resolve(here, '../../slotopol/katana_data.yaml');
const OUT = resolve(here, '../engine/config/reelSets.ts');

/**
 * The set the game deals. slotopol ships no _calc.lua for katana, so no set
 * is marked original; the provider publishes 94.95% for Katana and no set
 * sits on it. This is the set nearest to it (0.435pp above; the next,
 * 93.362435, is 1.588pp below).
 */
export const ORIGINAL_RTP = 95.385457;

/**
 * The yaml holds two documents: .../bon (the free-games strips, one flat
 * list of five) and .../rmap (one labelled block per base reel set).
 */
export function parseYaml(text) {
  let section = '';
  const bonus = [];
  const sets = [];
  let current = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trimEnd();
    const sec = /^novomatic\/katana\/(\w+)$/.exec(line);
    if (sec) {
      section = sec[1];
      continue;
    }
    const strip = /^\s*-\s*\[([\d,\s]*)\]$/.exec(line);
    if (strip) {
      const nums = strip[1].trim() === '' ? [] : strip[1].split(',').map((n) => Number(n.trim()));
      if (section === 'bon') bonus.push(nums);
      else if (section === 'rmap') {
        if (!current) throw new Error(`strip before any set label: ${line}`);
        current.reels.push(nums);
      } else throw new Error(`strip outside a known section: ${line}`);
      continue;
    }
    if (section === 'rmap') {
      const head = /^(\d+\.\d+):\s*$/.exec(line);
      if (head) {
        current = { rtp: Number(head[1]), reels: [] };
        sets.push(current);
      }
    }
  }
  return { bonus, sets };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { bonus, sets } = parseYaml(readFileSync(YAML, 'utf8'));
  if (sets.length === 0) throw new Error('no reel sets parsed');

  const checkSyms = (nums, what) => {
    if (nums.length === 0) throw new Error(`${what} has an empty strip`);
    for (const n of nums) if (!Number.isInteger(n) || n < 1 || n > 12) throw new Error(`${what} has bad symbol ${n}`);
  };
  for (const s of sets) {
    if (s.reels.length !== 5) throw new Error(`set ${s.rtp} has ${s.reels.length} reels, want 5`);
    s.reels.forEach((r) => checkSyms(r, `set ${s.rtp}`));
  }
  if (bonus.length !== 5) throw new Error(`free set has ${bonus.length} reels, want 5`);
  bonus.forEach((r) => checkSyms(r, 'free set'));
  if (!sets.some((s) => s.rtp === ORIGINAL_RTP)) throw new Error(`set ${ORIGINAL_RTP} missing from the yaml`);

  const fmtReels = (reels, indent) => reels.map((r) => `${indent}[${r.join(', ')}],`).join('\n');
  const lens = (reels) => reels.map((r) => r.length);

  const body = sets
    .map((s) => {
      const total = s.reels.reduce((a, r) => a * r.length, 1);
      const note =
        s.rtp === ORIGINAL_RTP
          ? `    // ACTIVE: the set nearest the provider's published 94.95%.\n` +
            `    // reels lengths [${lens(s.reels).join(', ')}], reshuffles ${total}\n`
          : `    // reels lengths [${lens(s.reels).join(', ')}], reshuffles ${total}\n`;
      return `  {\n${note}    rtp: ${s.rtp.toFixed(6)},\n    reels: [\n${fmtReels(s.reels, '      ')}\n    ],\n  },`;
    })
    .join('\n');

  const activeIndex = sets.findIndex((s) => s.rtp === ORIGINAL_RTP);

  const out = `import type { SymbolId } from '../types';
import { SYMBOL_ORDER } from '../types';

/**
 * GENERATED by src/sim/genReels.mjs from slotopol/katana_data.yaml.
 * Do not edit by hand; re-run \`npm run gen:reels\` instead, then
 * \`npm run sim:reels\` to prove the file still matches the yaml.
 *
 * Numeric symbol ids are slotopol's, 1-based, see SYMBOL_ORDER. Each rtp is
 * the label slotopol gives the set (base game plus free games), reproduced
 * to 6 decimals by src/sim/exact.ts and src/sim/parsheet.ts.
 */
const RAW: { rtp: number; reels: number[][] }[] = [
${body}
];

/**
 * The free-games strips (slotopol's .../bon), all five reels, lengths
 * [${lens(bonus).join(', ')}]. Every free game spins on these.
 */
const FREE_RAW: number[][] = [
${fmtReels(bonus, '  ')}
];

export interface ReelSet {
  /** slotopol's label for this set: its RTP in percent */
  rtp: number;
  /** reels[reel] = full strip of symbols */
  reels: SymbolId[][];
}

const toSymbols = (reel: number[]): SymbolId[] => reel.map((n) => SYMBOL_ORDER[n - 1]);

export const REEL_SETS: ReelSet[] = RAW.map((s) => ({ rtp: s.rtp, reels: s.reels.map(toSymbols) }));

/** The free-games strips by reel, 0-based. */
export const FREE_REELS: SymbolId[][] = FREE_RAW.map(toSymbols);

/** The set the game deals (${ORIGINAL_RTP.toFixed(6)}), see genReels.mjs. */
export const ACTIVE_REELS: ReelSet = REEL_SETS[${activeIndex}];
`;

  writeFileSync(OUT, out);
  console.log(
    `wrote ${OUT}\n${sets.length} base sets, labels ${sets[0].rtp}% to ${sets[sets.length - 1].rtp}%, ` +
      `active index ${activeIndex} (${ORIGINAL_RTP}), free strips [${lens(bonus).join(', ')}]`,
  );
}
