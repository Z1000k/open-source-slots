/**
 * Generate src/engine/config/reelSets.ts from the slotopol data file.
 *
 * The strips are read straight out of slotopol/columbus_data.yaml rather
 * than typed by hand, so there is no transcription to get wrong.
 * src/sim/checkReels.ts re-reads the same yaml afterwards and asserts the
 * generated TS still matches.
 *
 *   node src/sim/genReels.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const YAML = resolve(here, '../../slotopol/columbus_data.yaml');
const OUT = resolve(here, '../engine/config/reelSets.ts');

/**
 * The original Columbus Deluxe strips. slotopol ships no _calc.lua for
 * columbus, so the original is identified by the provider's published RTP:
 * Columbus Deluxe (10 lines, the layout ported here) is 95.02%, and this is
 * the only set within 0.5pp of it. (The 9-line Columbus of 2005 is published
 * at 97.03%, slotopol's 97.029053 set.)
 */
const ORIGINAL_RTP = 95.022795;

/**
 * The yaml holds the bonus strips first (unlabelled, under the .../bon key),
 * then one labelled block per regular reel set under .../rmap.
 */
export function parseYaml(text) {
  const bonus = [];
  const sets = [];
  let current = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trimEnd();
    const head = /^(\d+\.\d+):\s*$/.exec(line);
    if (head) {
      current = { rtp: Number(head[1]), reels: [] };
      sets.push(current);
      continue;
    }
    const strip = /^\s*-\s*\[([\d,\s]+)\]\s*$/.exec(line);
    if (strip) {
      const nums = strip[1].split(',').map((n) => Number(n.trim()));
      (current ? current.reels : bonus).push(nums);
    }
  }
  return { bonus, sets };
}

const { bonus, sets } = parseYaml(readFileSync(YAML, 'utf8'));
if (sets.length === 0) throw new Error('no reel sets parsed');

const check = (reels, what) => {
  if (reels.length !== 5) throw new Error(`${what} has ${reels.length} reels, want 5`);
  for (const r of reels) {
    for (const n of r) {
      if (!Number.isInteger(n) || n < 1 || n > 10) throw new Error(`${what} has bad symbol ${n}`);
    }
  }
};
check(bonus, 'bonus set');
for (const s of sets) check(s.reels, `set ${s.rtp}`);
if (!sets.some((s) => s.rtp === ORIGINAL_RTP)) {
  throw new Error(`original set ${ORIGINAL_RTP} missing from the yaml`);
}

const fmtReels = (reels, indent) => reels.map((r) => `${indent}[${r.join(', ')}],`).join('\n');

const body = sets
  .map((s) => {
    const lens = s.reels.map((r) => r.length);
    const total = lens.reduce((a, b) => a * b, 1);
    const note =
      s.rtp === ORIGINAL_RTP
        ? `    // ORIGINAL Columbus Deluxe strips (the provider publishes 95.02%).\n` +
          `    // reels lengths [${lens.join(', ')}], reshuffles ${total}\n`
        : `    // reels lengths [${lens.join(', ')}], reshuffles ${total}\n`;
    return `  {\n${note}    rtp: ${s.rtp.toFixed(6)},\n    reels: [\n${fmtReels(s.reels, '      ')}\n    ],\n  },`;
  })
  .join('\n');

const activeIndex = sets.findIndex((s) => s.rtp === ORIGINAL_RTP);
const bonusLens = bonus.map((r) => r.length);
const bonusTotal = bonusLens.reduce((a, b) => a * b, 1);

const out = `import type { SymbolId } from '../types';
import { SYMBOL_ORDER } from '../types';

/**
 * GENERATED by src/sim/genReels.mjs from slotopol/columbus_data.yaml.
 * Do not edit by hand; re-run \`npm run gen:reels\` instead, then
 * \`npm run sim:reels\` to prove the file still matches the yaml.
 *
 * Numeric symbol ids are slotopol's, 1-based, see SYMBOL_ORDER. Each rtp is
 * the full-game figure slotopol publishes for that set (base symbols plus the
 * free games it triggers); src/sim/exact.ts and src/sim/parsheet.ts reproduce
 * every one of them.
 */
const RAW: { rtp: number; reels: number[][] }[] = [
${body}
];

/**
 * The free games strips, shared by every set.
 * reels lengths [${bonusLens.join(', ')}], reshuffles ${bonusTotal}.
 * slotopol publishes 251.427957% per free game awarded, retriggers included
 * (GALLEON wild on the lines, no multiplier).
 */
const BONUS_RAW: number[][] = [
${fmtReels(bonus, '  ')}
];

export interface ReelSet {
  /** the RTP slotopol publishes for this set, in percent */
  rtp: number;
  /** reels[reel] = full strip of symbols */
  reels: SymbolId[][];
}

const toSymbols = (reels: number[][]): SymbolId[][] =>
  reels.map((r) => r.map((n) => SYMBOL_ORDER[n - 1]));

export const REEL_SETS: ReelSet[] = RAW.map((s) => ({ rtp: s.rtp, reels: toSymbols(s.reels) }));

/** The free games strips, used for every spin of a bonus session. */
export const BONUS_REELS: SymbolId[][] = toSymbols(BONUS_RAW);

/** The original Columbus Deluxe reels (${ORIGINAL_RTP.toFixed(6)}%) - the set the game deals. */
export const ACTIVE_REELS: ReelSet = REEL_SETS[${activeIndex}];
`;

writeFileSync(OUT, out);
console.log(
  `wrote ${OUT}\n${sets.length} reel sets, RTP ${sets[0].rtp}% to ${sets[sets.length - 1].rtp}%, ` +
    `active index ${activeIndex} (${ORIGINAL_RTP}%), bonus strips [${bonusLens.join(', ')}]`,
);
